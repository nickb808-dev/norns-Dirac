-- dirac
--
-- granular processor
-- ported from the ER-301
--
-- E1  scroll params
-- K1+ norns menu
--
-- Phase 2: the params menu
-- IS the interface. The cell
-- UI arrives in phase 3.

engine.name = "Dirac"

local SPEC = include("norns-dirac/lib/params")

local OPTIONS = {
  -- 1-based, matching od::OptionControl on the ER-301. The engine compares
  -- against literal 1/2/3, so index 0 would select nothing at all.
  { id = "playheadsOpt", name = "playheads",  choices = { "single", "multi" },  default = 1 },
  { id = "diffuseOpt",   name = "diffuse",    choices = { "off", "on" },        default = 1 },
  { id = "freezeOpt",    name = "capture",    choices = { "run", "freeze" },    default = 1 },
}

local dirty = true

function init()
  -- Parameters are built from lib/params.lua rather than written out here, so
  -- the ranges cannot drift from the ER-301's. A hand-written second copy is
  -- exactly how Speed, Heads, Grains and Tilt ended up wrong the first time.
  for _, p in ipairs(SPEC) do
    local step = p.step or 0
    params:add_control(
      p.id, p.name,
      controlspec.new(p.min, p.max, p.warp or "lin", step, p.default, p.unit or ""))
    params:set_action(p.id, function(x)
      -- engine.<id> is generated by matron from Engine_Dirac.sc's addCommand
      -- list. If a command is missing this is nil and the parameter moves in
      -- the menu while nothing happens — hence tools/check-params.sh.
      engine[p.id](x)
      dirty = true
    end)
  end

  for _, o in ipairs(OPTIONS) do
    params:add_option(o.id, o.name, o.choices, o.default)
    params:set_action(o.id, function(i)
      engine[o.id](i)
      dirty = true
    end)
  end

  params:bang()

  clock.run(function()
    while true do
      clock.sleep(1 / 15)
      if dirty then redraw(); dirty = false end
    end
  end)
end

function redraw()
  screen.clear()
  screen.level(15)
  screen.move(0, 10)
  screen.text("dirac")
  screen.level(3)
  screen.move(0, 22)
  screen.text("granular processor")

  -- Phase 2 has no custom UI by design: the exit criterion is that every
  -- parameter is reachable and audible, and the params menu already does that.
  -- Showing a few live values is enough to confirm the engine is being driven
  -- without pretending this is the finished interface.
  screen.level(15)
  screen.move(0, 40)
  screen.text("dens " .. string.format("%.1f", params:get("rate")))
  screen.move(52, 40)
  screen.text("len " .. string.format("%.3f", params:get("grainlen")))
  screen.move(0, 50)
  screen.text("mix " .. string.format("%.2f", params:get("mix")))
  screen.move(52, 50)
  screen.text("lvl " .. string.format("%.2f", params:get("level")))
  screen.level(3)
  screen.move(0, 62)
  screen.text("K1 + E1 for params")
  screen.update()
end

function cleanup()
end
